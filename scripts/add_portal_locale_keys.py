def jq(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def strip_comments(raw: str) -> str:
    if raw.lstrip("\ufeff").startswith("/*"):
        raw = raw[raw.index("*/") + 2:]
    return re.sub(r"^\s*//.*$", "", raw, flags=re.M)


def insert_after_portal(raw: str, block: str) -> str:
    """在 "portal": { 行后插入 block,跟随该行自身的换行风格(容忍 \\r\\n 混排)。"""
    lines = raw.split("\n")
    out = []
    inserted = False
    for line in lines:
        out.append(line)
        if not inserted and re.match(r'^\s{2}"portal":\s*\{\s*$', line.rstrip("\r")):
            eol = "\r\n" if line.endswith("\r") else ""
            out.append(block.rstrip("\n").replace("\n", eol) if eol else block.rstrip("\n"))
            inserted = True
    if not inserted:
        raise SystemExit("FATAL: portal block not found")
    return "\n".join(out)


def process(path: str, lang: str, kind: str) -> str:
    with io.open(path, "r", encoding="utf-8", newline="") as f:
        raw = f.read()
    has_bom = raw.startswith("\ufeff")
    t = TR["en" if lang == "en.default" else lang]
    if kind == "storefront":
        if '"not_found"' in raw:
            return "skip"
        block = STOREFRONT_TEMPLATE.format(
            **{k: jq(t[k]) for k in KEY_ORDER if not k.startswith("sc_")}
        )
    else:
        if '"faq_structured_data"' in raw:
            return "skip"
        block = SCHEMA_TEMPLATE.format(
            **{k: jq(t[k]) for k in KEY_ORDER if k.startswith("sc_")}
        )
    new = insert_after_portal(raw, block)
    # 校验 JSON 合法性(容忍注释)
    json.loads(strip_comments(new))
    with io.open(path, "w", encoding="utf-8-sig" if has_bom else "utf-8", newline="") as f:
        f.write(new)
    return "ok"


stats = {"ok": 0, "skip": 0}
import glob
import os

for f in sorted(glob.glob(os.path.join("locales", "*.json"))):
    name = os.path.basename(f)
    lang = name[:-5]
    if name.endswith(".schema.json"):
        lang = name[: -len(".schema.json")]
        kind = "schema"
        if lang not in TR and lang != "en.default":
            print(f"WARN no translation for schema {lang}, using en")
    else:
        kind = "storefront"
        if lang not in TR and lang != "en.default":
            print(f"WARN no translation for {lang}, using en")
    try:
        r = process(f, lang, kind)
    except SystemExit as e:
        print(f"FAIL {name}: {e}")
        sys.exit(1)
    stats[r] = stats.get(r, 0) + 1
    if r == "skip":
        print(f"skip {name}")

print("done:", stats)
